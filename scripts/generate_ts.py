#!/usr/bin/env python3
"""Generate ``euler_metric_naming/contract/ts/euler-contract.data.ts`` from the JSON.

The TS artifact's data (closed set, vocabularies, legacy table, schemas) is
generated from the package's sources of truth so both languages ship the same
contract.

    python scripts/generate_ts.py          # write
    python scripts/generate_ts.py --check  # exit 1 when out of date
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from euler_metric_naming import __version__  # noqa: E402
from euler_metric_naming.contract import (  # noqa: E402
    closed_sets,
    legacy_table,
    vocabulary_documents,
)

CONTRACT = ROOT / "euler_metric_naming" / "contract"
TARGET = CONTRACT / "ts" / "euler-contract.data.ts"

HEADER = """\
// GENERATED FILE -- do not edit.
// Generated by scripts/generate_ts.py (euler-metric-naming {version}) from
// contract/closed.py, contract/vocabularies/*.json, contract/legacy/protocol-1.json
// and contract/schema/*.json. Regenerate with: python scripts/generate_ts.py

/** A JSON value as stored in this file. */
export type GeneratedJson =
\t| null
\t| boolean
\t| number
\t| string
\t| readonly GeneratedJson[]
\t| {{ readonly [key: string]: GeneratedJson }};

/** The euler-metric-naming version this data was generated from. */
export const CONTRACT_PACKAGE_VERSION = {version_json};
"""


def _json(value) -> str:
    text = json.dumps(value, indent="\t", ensure_ascii=False, sort_keys=False)
    return text


def render() -> str:
    schemas = {
        name: json.loads((CONTRACT / "schema" / name).read_text(encoding="utf-8"))
        for name in (
            "protocol-2.schema.json",
            "vocabulary-1.schema.json",
            "training-naming-2.schema.json",
            "validation-set-1.schema.json",
            "validation-pass-1.schema.json",
        )
    }
    parts = [
        HEADER.format(version=__version__, version_json=json.dumps(__version__)),
        "/** The closed set of section 3 (contract/closed.py). */",
        f"export const CLOSED_SETS = {_json(closed_sets())} as const;",
        "",
        "/** The shipped vocabularies by id (contract/vocabularies). */",
        "export const VOCABULARIES: { readonly [id: string]: GeneratedJson } = "
        f"{_json(vocabulary_documents())};",
        "",
        "/** The frozen schema-1 adapter table (contract/legacy/protocol-1.json). */",
        f"export const LEGACY_PROTOCOL_1: GeneratedJson = {_json(legacy_table())};",
        "",
        "/** JSON Schema of the protocol block (contract/schema/protocol-2.schema.json). */",
        f"export const PROTOCOL_SCHEMA: GeneratedJson = {_json(schemas['protocol-2.schema.json'])};",
        "",
        "/** JSON Schema of vocabulary documents (contract/schema/vocabulary-1.schema.json). */",
        f"export const VOCABULARY_SCHEMA: GeneratedJson = {_json(schemas['vocabulary-1.schema.json'])};",
        "",
        "/** JSON Schema of training naming 2.0 declarations (contract/schema/training-naming-2.schema.json). */",
        "export const TRAINING_NAMING_SCHEMA: GeneratedJson = "
        f"{_json(schemas['training-naming-2.schema.json'])};",
        "",
        "/** JSON Schema of validation set documents (contract/schema/validation-set-1.schema.json). */",
        "export const VALIDATION_SET_SCHEMA: GeneratedJson = "
        f"{_json(schemas['validation-set-1.schema.json'])};",
        "",
        "/** JSON Schema of validation pass records (contract/schema/validation-pass-1.schema.json). */",
        "export const VALIDATION_PASS_SCHEMA: GeneratedJson = "
        f"{_json(schemas['validation-pass-1.schema.json'])};",
        "",
    ]
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the file is out of date")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print(f"{TARGET.relative_to(ROOT)} is out of date; run scripts/generate_ts.py")
            return 1
        print("TS data up to date")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
